#ifndef RIN_KERNEL_RIN_CRYPT_KEYSLOT_H
#define RIN_KERNEL_RIN_CRYPT_KEYSLOT_H

#include <stdint.h>

#include <rinruntime/crypt/volume.h>

#define RIN_CRYPT_KEYSLOT_MAGIC UINT32_C(0x31534b52) /* "RKS1" */
#define RIN_CRYPT_KEYSLOT_VERSION 1u
#define RIN_CRYPT_KEYSLOT_AAD_SIZE 92u
#define RIN_CRYPT_KEYSLOT_SERIALIZED_SIZE 172u
#define RIN_CRYPT_KEYSLOT_SALT_SIZE 16u
#define RIN_CRYPT_KEYSLOT_NONCE_SIZE 12u
#define RIN_CRYPT_KEYSLOT_KEK_SIZE 32u
#define RIN_CRYPT_KEYSLOT_MIN_PASSWORD_SIZE 8u
#define RIN_CRYPT_KEYSLOT_MAX_PASSWORD_SIZE 1024u
#define RIN_CRYPT_KEYSLOT_MIN_MEMORY_KIB 19456u
#define RIN_CRYPT_KEYSLOT_MAX_MEMORY_KIB 1048576u
#define RIN_CRYPT_KEYSLOT_MIN_TIME_COST 2u
#define RIN_CRYPT_KEYSLOT_MAX_TIME_COST 10u
#define RIN_CRYPT_KEYSLOT_MAX_LANES 4u
#define RIN_CRYPT_KEYSLOT_PAIR_COUNT 2u
#define RIN_CRYPT_KEYSLOT_PROVIDER_MAGIC UINT32_C(0x31504b52) /* "RKP1" */

/* All integers are little-endian byte strings. This is an on-disk format, so
 * it deliberately has no compiler padding or native-endian integer fields. */
typedef struct RinCryptKeyslotV1 {
    uint8_t magic[4];
    uint8_t version[2];
    uint8_t header_size[2];
    uint8_t memory_kib[4];
    uint8_t time_cost[4];
    uint8_t lanes[4];
    uint8_t reserved[4];
    uint8_t key_epoch[8];
    uint8_t volume_id[RIN_CRYPT_VOLUME_ID_SIZE];
    uint8_t keyslot_id[RIN_CRYPT_KEYSLOT_ID_SIZE];
    uint8_t salt[RIN_CRYPT_KEYSLOT_SALT_SIZE];
    uint8_t nonce[RIN_CRYPT_KEYSLOT_NONCE_SIZE];
    uint8_t wrapped_key[RIN_CRYPT_XTS_256_KEY_SIZE];
    uint8_t tag[16];
} RinCryptKeyslotV1;

typedef struct RinCryptKeyslotParametersV1 {
    uint32_t memory_kib;
    uint32_t time_cost;
    uint32_t lanes;
    uint32_t reserved;
} RinCryptKeyslotParametersV1;

typedef int (*RinCryptKeyslotRandomFn)(void* context, uint8_t* output,
                                       uint32_t size);

/* Synchronous consumer for the shared key generated by pair enrollment.
 * The callback may use the key only for the duration of the call and must
 * return RIN_CRYPT_OK only after its own output is complete. The primary
 * keyslot is the first (normally password) slot. */
typedef int (*RinCryptKeyslotPairSealFn)(
    void* context,
    const uint8_t volume_id[RIN_CRYPT_VOLUME_ID_SIZE],
    const uint8_t primary_keyslot_id[RIN_CRYPT_KEYSLOT_ID_SIZE],
    uint64_t key_epoch,
    const uint8_t key[RIN_CRYPT_XTS_256_KEY_SIZE]);

typedef struct RinCryptKeyslotProvider {
    volatile uint32_t lock;
    uint32_t magic;
    uint32_t active;
    uint32_t attempted;
    RinCryptKeyslotV1 keyslot;
    uint8_t* password;
    uint32_t password_size;
    uint32_t reserved;
    uint8_t* workspace;
    uint64_t workspace_size;
} RinCryptKeyslotProvider;

#if defined(__cplusplus)
static_assert(sizeof(RinCryptKeyslotV1) == RIN_CRYPT_KEYSLOT_SERIALIZED_SIZE,
              "RinCrypt keyslot format drift");
#elif defined(__STDC_VERSION__) && __STDC_VERSION__ >= 201112L
_Static_assert(sizeof(RinCryptKeyslotV1) == RIN_CRYPT_KEYSLOT_SERIALIZED_SIZE,
               "RinCrypt keyslot format drift");
#endif

/* Formatting consumes and clears password. The random callback must be a
 * trusted CSPRNG; weak/random fallback sources are not accepted here. */
int rin_crypt_keyslot_format_v1(
    RinCryptKeyslotV1* keyslot,
    const uint8_t volume_id[RIN_CRYPT_VOLUME_ID_SIZE],
    const uint8_t keyslot_id[RIN_CRYPT_KEYSLOT_ID_SIZE],
    const RinCryptKeyslotParametersV1* parameters, uint8_t* password,
    uint32_t password_size, RinCryptKeyslotRandomFn random_bytes,
    void* random_context, uint8_t* workspace, uint64_t workspace_size);

/* Formats the two on-disk header slots around one CSPRNG-generated XTS key
 * and epoch. On every non-alias path both mutable passwords are consumed and
 * cleared. The output slots, credentials, immutable inputs, and Argon
 * workspace must be pairwise disjoint; aliases are rejected before mutation. */
int rin_crypt_keyslot_format_pair_v1(
    RinCryptKeyslotV1 keyslots[RIN_CRYPT_KEYSLOT_PAIR_COUNT],
    const uint8_t volume_id[RIN_CRYPT_VOLUME_ID_SIZE],
    const uint8_t first_keyslot_id[RIN_CRYPT_KEYSLOT_ID_SIZE],
    const RinCryptKeyslotParametersV1* first_parameters,
    uint8_t* first_password, uint32_t first_password_size,
    const uint8_t second_keyslot_id[RIN_CRYPT_KEYSLOT_ID_SIZE],
    const RinCryptKeyslotParametersV1* second_parameters,
    uint8_t* second_password, uint32_t second_password_size,
    RinCryptKeyslotRandomFn random_bytes, void* random_context,
    uint8_t* workspace, uint64_t workspace_size);

/* Pair formatting with a mandatory synchronous seal transaction. Both
 * keyslots are discarded if the callback fails or mutates any snapshotted
 * identity, key material, or completed keyslot. */
int rin_crypt_keyslot_format_pair_and_seal_v1(
    RinCryptKeyslotV1 keyslots[RIN_CRYPT_KEYSLOT_PAIR_COUNT],
    const uint8_t volume_id[RIN_CRYPT_VOLUME_ID_SIZE],
    const uint8_t first_keyslot_id[RIN_CRYPT_KEYSLOT_ID_SIZE],
    const RinCryptKeyslotParametersV1* first_parameters,
    uint8_t* first_password, uint32_t first_password_size,
    const uint8_t second_keyslot_id[RIN_CRYPT_KEYSLOT_ID_SIZE],
    const RinCryptKeyslotParametersV1* second_parameters,
    uint8_t* second_password, uint32_t second_password_size,
    RinCryptKeyslotPairSealFn seal_key, void* seal_context,
    RinCryptKeyslotRandomFn random_bytes, void* random_context,
    uint8_t* workspace, uint64_t workspace_size);

int rin_crypt_keyslot_validate_v1(const RinCryptKeyslotV1* keyslot);

/* Initialization takes ownership of the mutable password until unlock or
 * clear. Unlock is deliberately one-shot and always clears the password. */
int rin_crypt_keyslot_provider_init(RinCryptKeyslotProvider* provider,
                                    const RinCryptKeyslotV1* keyslot,
                                    uint8_t* password,
                                    uint32_t password_size,
                                    uint8_t* workspace,
                                    uint64_t workspace_size);
void rin_crypt_keyslot_provider_clear(RinCryptKeyslotProvider* provider);
const RinCryptKeyProviderV1* rin_crypt_keyslot_provider_api(void);

#endif /* RIN_KERNEL_RIN_CRYPT_KEYSLOT_H */
